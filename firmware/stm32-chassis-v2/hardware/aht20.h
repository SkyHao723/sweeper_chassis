#ifndef __AHT20_H
#define __AHT20_H

/**
  ******************************************************************************
  * @file    aht20.h
  * @brief   AHT20 温湿度传感器 (走 PB8/PB9 软件 I2C, 与 OLED 同一条总线)
  *
  * 关键点:
  *   1) 上电后要等 40ms 才能通信, 且第一次读到状态位 bit3(CAL)=0 时要发一次校准命令
  *   2) 触发测量(0xAC 0x33 0x00)后必须等 ~80ms 才能读结果, 所以这里做成
  *      "触发 -> 轮询" 两步, 不在里面死等, 免得卡住主循环(按键/串口都会顿)
  *   3) 结果 20bit: 湿度 = raw / 2^20 * 100 (%RH), 温度 = raw / 2^20 * 200 - 50 (°C)
  ******************************************************************************
  */

#include "stm32f10x.h"

#define AHT20_I2C_ADDRESS 0x70u /* 0x38 << 1 */
#define AHT20_TRIGGER_MS 80u    /* 触发后要等的时间, 留点余量 */

/* 总线初始化(由 SoftI2c_Init 完成, 这里只是把 AHT20 上电时序走一遍)。1 = 成功 */
uint8_t Aht20_Init(void);

/* 触发一次测量(不阻塞)。返回 1 = 命令已发出 */
uint8_t Aht20_Trigger(void);

/* 轮询读取结果: 到时间且读成功时返回 1, 并填好 temp_c100 / rh_100
   (单位分别是 0.01°C 和 0.01%RH)。没到时间或还没成功返回 0。 */
uint8_t Aht20_Poll(int16_t *temp_c100, uint16_t *rh_100);

/* 最近一次是否成功读到过 (供屏幕显示 OK / ERR) */
uint8_t Aht20_IsOk(void);

/* 是否至少成功解析出过一次有效温湿度 (遥测帧里用这个当 aht_ok 标志) */
uint8_t Aht20_HasSample(void);

#endif
